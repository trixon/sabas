    public void activateFilter() {
        if (filterTextField != null) {
            filterTextField.requestFocusInWindow();
            filterTextField.selectAll();
        }
    }

    @Override
    public boolean filter(Pkg pkg) {
        var validAppstream = !appstreamCheckBox.isSelected() || pkg.hasAppStream();
        var validStartable = !startableCheckBox.isSelected() || pkg.isStartable();

        return validAppstream
                && validStartable;
    }

    @Override
    public void reset() {
        filterTextField.setText("");
        List.of(
                summaryCheckBox,
                descriptionCheckBox,
                appstreamCheckBox,
                startableCheckBox
        )
                .forEach(cb -> cb.setSelected(false));
    }

