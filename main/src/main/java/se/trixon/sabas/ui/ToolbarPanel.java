    private void initListeners() {
        filterTextField.getDocument().addDocumentListener(new DocumentListener() {
            @Override
            public void insertUpdate(DocumentEvent e) {
                requestFiltering();
            }

            @Override
            public void removeUpdate(DocumentEvent e) {
                requestFiltering();
            }

            @Override
            public void changedUpdate(DocumentEvent e) {
            }

        });
    }

    private void requestFiltering() {
        mFilterManager.setText(filterTextField.getText());
        mFilterManager.setFilterDescription(descriptionCheckBox.isSelected());
        mFilterManager.setFilterSummary(summaryCheckBox.isSelected());

        mFilterManager.requestFiltering();
    }

